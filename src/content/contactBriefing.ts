import { AUTO_CALL_SUPPORTED } from './autoCall';

/**
 * ההודעה שההורה שולח לאיש הקשר לחירום, כדי שיידע מה פירוש שיחה מהאפליקציה.
 *
 * בקשת הבעלים (24.11): כשהאפליקציה מתקשרת, איש הקשר מקבל שיחה שקטה מהמספר של
 * ההורה - אף אחד לא מדבר, כי ההורה לא ליד הטלפון. בלי ההסבר הזה הוא עלול
 * לחשוב שזו שיחה בטעות ולנתק. ההודעה אומרת לו בדיוק מה לעשות.
 *
 * ניסוח: לעולם לא "שכחת ילד" - האפליקציה לא יודעת שיש ילד ברכב.
 * ניטרלי מגדרית, כי לא יודעים מי איש הקשר.
 */
export function buildContactBriefing(
  contactName: string,
  parentName: string,
  autoCall: boolean = AUTO_CALL_SUPPORTED
): string {
  const hello = contactName.trim() ? `היי ${contactName.trim()},` : 'היי,';
  const signature = parentName.trim() ? `תודה! ${parentName.trim()}` : 'תודה!';

  const lines = [
    hello,
    'הגדרתי אותך כאיש קשר לחירום באפליקציית Little Shield, שעוזרת לי לזכור לבדוק שכל הילדים יצאו מהרכב.',
    '',
  ];

  if (autoCall) {
    lines.push(
      'אם תגיע אליך ממני שיחה ואף אחד לא מדבר - זו שיחה אוטומטית מהאפליקציה. היא אומרת שיצאתי מהרכב ולא אישרתי שראיתי את האזהרות.',
      '',
      'מה לעשות:',
      '1. להתקשר אליי מיד.',
      '2. אם אני לא עונה - לוודא, דרכי או דרך מישהו קרוב, שאף ילד לא נשאר ברכב.'
    );
  } else {
    lines.push(
      'אם אתקשר אליך מתוך האפליקציה, ייתכן שאני צריך עזרה לוודא שאף ילד לא נשאר ברכב.',
      'אם התקשרתי ולא דיברתי - תתקשר אליי בחזרה.'
    );
  }

  lines.push('', signature);
  return lines.join('\n');
}
